package main

import (
    "fmt"
    "os"
)

var fArgs []string

func argsList() []string {
    if len(fArgs) > 0 { return fArgs }
    if len(os.Args) > 1 { return os.Args[1:] }
    return nil
}

func paramAt(i int) string {
    a := argsList()
    if i >= 1 && i <= len(a) { return a[i-1] }
    return ""
}

func main() {
    fmt.Println(fmt.Sprintf("Invalid configuration `%v\\': more than four components", paramAt(1))); // line 3
    os.Exit(int(1)); // line 4
    return;
}
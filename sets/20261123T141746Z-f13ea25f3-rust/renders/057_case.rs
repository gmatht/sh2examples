use std::sync::atomic::Ordering;

static __SH_RC: std::sync::atomic::AtomicI32 = std::sync::atomic::AtomicI32::new(0);
static __SH_ARGV: std::sync::Mutex<Vec<String>> = std::sync::Mutex::new(Vec::new());
static __SH_OUT: std::sync::Mutex<Option<Vec<u8>>> = std::sync::Mutex::new(None);
thread_local! { static __SH_OUTFILE_TL: std::cell::RefCell<Option<std::fs::File>> = const { std::cell::RefCell::new(None) }; }
static __SH_STDIN: std::sync::Mutex<Option<Box<dyn std::io::Read + Send>>> = std::sync::Mutex::new(None);
static __SH_STDIN_PATH: std::sync::Mutex<Option<std::path::PathBuf>> = std::sync::Mutex::new(None);

static __SH_TRAPS: std::sync::Mutex<Vec<String>> = std::sync::Mutex::new(Vec::new());

thread_local! { #[allow(non_upper_case_globals)] static __SHV_filename: std::cell::RefCell<String> = const { std::cell::RefCell::new(String::new()) }; }

fn __sh_spawn(cmd: &str, input: Option<&[u8]>) -> i32 {
    let mut input = input.map(|d| d.to_vec());
    let stdin_path = __SH_STDIN_PATH.lock().unwrap().clone();
    if input.is_none() && stdin_path.is_none() {
        if let Some(mut r) = __SH_STDIN.lock().unwrap().take() {
            let mut d = Vec::new();
            let _ = std::io::Read::read_to_end(&mut r, &mut d);
            input = Some(d);
        }
    }
    let want_out = __SH_OUT.lock().unwrap().is_some() || __SH_OUTFILE_TL.with(|v| v.borrow().is_some());
    let mut c = std::process::Command::new("bash");
    c.arg("-c").arg(cmd);
    if !want_out {
        let _ = std::io::Write::flush(&mut std::io::stdout());
    }
    if want_out { c.stdout(std::process::Stdio::piped()); }
    if input.is_none() {
        if let Some(p) = &stdin_path {
            if let Ok(f) = std::fs::File::open(p) {
                c.stdin(std::process::Stdio::from(f));
            }
        }
    }
    if input.is_some() { c.stdin(std::process::Stdio::piped()); }
    let Ok(mut ch) = c.spawn() else { return 1 };
    if let Some(data) = input {
        if let Some(mut si) = ch.stdin.take() { let _ = std::io::Write::write_all(&mut si, &data); }
    }
    let mut out = Vec::new();
    if let Some(mut so) = ch.stdout.take() {
        let _ = std::io::Read::read_to_end(&mut so, &mut out);
    }
    let rc = ch.wait().map(|s| s.code().unwrap_or(1)).unwrap_or(1);
    if !out.is_empty() { __sh_sink(&out); }
    rc
}

fn __sh_run(cmd: &str) -> i32 {
    __sh_spawn(cmd, None)
}

fn __sh_fnmatch(pat: &str, s: &str) -> bool {
    let pat = pat.split('\0').next().unwrap_or(pat);
    let p: Vec<char> = pat.chars().collect();
    let t: Vec<char> = s.chars().collect();
    fn class_pred(n: &str) -> Option<fn(char) -> bool> {
        Some(match n {
            "alnum" => |c: char| c.is_alphanumeric(),
            "alpha" => |c: char| c.is_alphabetic(),
            "blank" => |c: char| c == ' ' || c == '\t',
            "cntrl" => |c: char| c.is_control(),
            "digit" => |c: char| c.is_ascii_digit(),
            "graph" => |c: char| !c.is_whitespace() && !c.is_control(),
            "lower" => |c: char| c.is_lowercase(),
            "print" => |c: char| !c.is_control(),
            "punct" => |c: char| c.is_ascii_punctuation(),
            "space" => |c: char| c.is_whitespace(),
            "upper" => |c: char| c.is_uppercase(),
            "xdigit" => |c: char| c.is_ascii_hexdigit(),
            _ => return None,
        })
    }
    fn m(p: &[char], t: &[char]) -> bool {
        if p.is_empty() { return t.is_empty(); }
        match p[0] {
            '*' => {
                for i in 0..=t.len() { if m(&p[1..], &t[i..]) { return true; } }
                false
            }
            '?' => !t.is_empty() && m(&p[1..], &t[1..]),
            '[' => {
                if t.is_empty() { return false; }
                let mut j = 1;
                let neg = j < p.len() && (p[j] == '!' || p[j] == '^');
                if neg { j += 1; }
                let mut matched = false;
                let mut first = true;
                while j < p.len() && (p[j] != ']' || first) {
                    first = false;
                    if p[j] == '[' && j + 1 < p.len() && p[j + 1] == ':' {
                        if let Some(rel) = p[j + 2..].windows(2).position(|w| w == [':', ']']) {
                            let name: String = p[j + 2..j + 2 + rel].iter().collect();
                            if let Some(pred) = class_pred(&name) {
                                if pred(t[0]) { matched = true; }
                                j += rel + 4;
                                continue;
                            }
                        }
                    }
                    if j + 2 < p.len() && p[j + 1] == '-' && p[j + 2] != ']' {
                        if t[0] >= p[j] && t[0] <= p[j + 2] { matched = true; }
                        j += 3;
                    } else {
                        if t[0] == p[j] { matched = true; }
                        j += 1;
                    }
                }
                if j < p.len() && p[j] == ']' { j += 1; }
                if matched != neg { m(&p[j..], &t[1..]) } else { false }
            }
            '\\' => p.len() > 1 && !t.is_empty() && t[0] == p[1] && m(&p[2..], &t[1..]),
            c if (c == '@' || c == '?' || c == '*' || c == '+' || c == '!')
                && p.len() > 1 && p[1] == '(' => {
                let mut depth = 1;
                let mut j = 2;
                let mut alts: Vec<Vec<char>> = Vec::new();
                let mut cur: Vec<char> = Vec::new();
                while j < p.len() && depth > 0 {
                    match p[j] {
                        '(' => { depth += 1; cur.push(p[j]); }
                        ')' => {
                            depth -= 1;
                            if depth == 0 {
                                alts.push(cur.clone());
                            } else { cur.push(p[j]); }
                        }
                        '|' if depth == 1 => { alts.push(std::mem::take(&mut cur)); }
                        ch => cur.push(ch),
                    }
                    j += 1;
                }
                if depth != 0 { return false; }
                let rest = &p[j..];
                match c {
                    '@' => {
                        for a in &alts {
                            let mut joined = a.clone();
                            joined.extend_from_slice(rest);
                            if m(&joined, t) { return true; }
                        }
                        false
                    }
                    '?' => {
                        if m(rest, t) { return true; }
                        for a in &alts {
                            let mut joined = a.clone();
                            joined.extend_from_slice(rest);
                            if m(&joined, t) { return true; }
                        }
                        false
                    }
                    '*' => {
                        if m(rest, t) { return true; }
                        for a in &alts {
                            for i in 1..=t.len() {
                                if m(a, &t[..i]) && m(p, &t[i..]) { return true; }
                            }
                        }
                        false
                    }
                    '+' => {
                        for a in &alts {
                            for i in 1..=t.len() {
                                if m(a, &t[..i]) && m(p, &t[i..]) { return true; }
                            }
                        }
                        false
                    }
                    _ => {
                        for i in 0..=t.len() {
                            if m(rest, &t[i..]) {
                                let mut ok = true;
                                for a in &alts {
                                    if m(a, &t[..i]) { ok = false; break; }
                                }
                                if ok { return true; }
                            }
                        }
                        false
                    }
                }
            }
            c => !t.is_empty() && t[0] == c && m(&p[1..], &t[1..]),
        }
    }
    m(&p, &t)
}

fn __sh_arg(i: usize) -> String {
    __SH_ARGV.lock().unwrap().get(i).cloned().unwrap_or_default()
}

fn __sh_run_traps() {
    let hs = std::mem::take(&mut *__SH_TRAPS.lock().unwrap());
    for h in hs { let _ = __sh_spawn(&h, None); }
}

fn __sh_sink(b: &[u8]) {
    let mut used = false;
    __SH_OUTFILE_TL.with(|v| { if let Some(f) = v.borrow_mut().as_mut() { let _ = std::io::Write::write_all(f, b); used = true; } });
    if used { return; }
    if let Some(o) = __SH_OUT.lock().unwrap().as_mut() { o.extend_from_slice(b); return; }
    let _ = std::io::Write::write_all(&mut std::io::stdout(), b);
}

#[allow(non_upper_case_globals)]
fn main() -> std::process::ExitCode {
    print!("=== Basic Case Statement Example ===\n");
    if __sh_arg(0) == "start".to_string() {
        print!("Starting the service...\n");
    } else if __sh_arg(0) == "stop".to_string() {
        print!("Stopping the service...\n");
    } else if __sh_arg(0) == "restart".to_string() {
        print!("Restarting the service...\n");
    } else {
        println!("Usage: {} {{start|stop|restart}}", std::env::args().next().unwrap_or_default());
        __sh_run_traps();
        std::process::exit(1);
    }
    print!("=== Case Statement with Pattern Matching ===\n");
    __SHV_filename.with(|v| *v.borrow_mut() = __sh_arg(1));
    if __SHV_filename.with(|v| v.borrow().clone()).ends_with(".txt") {
        println!("Processing text file: {}", __SHV_filename.with(|v| v.borrow().clone()));
    } else if __SHV_filename.with(|v| v.borrow().clone()).ends_with(".sh") {
        println!("Processing shell script: {}", __SHV_filename.with(|v| v.borrow().clone()));
    } else if __SHV_filename.with(|v| v.borrow().clone()).ends_with(".py") {
        println!("Processing Python file: {}", __SHV_filename.with(|v| v.borrow().clone()));
    } else {
        println!("Unknown file type: {}", __SHV_filename.with(|v| v.borrow().clone()));
    }
    print!("=== Case Statement with Multiple Patterns ===\n");
    if (((__sh_arg(2) == "help".to_string()) || (__sh_arg(2) == "h".to_string())) || (__sh_arg(2) == "-h".to_string())) || (__sh_arg(2) == "--help".to_string()) {
        print!("Help information:\n");
        print!("  start  - Start the service\n");
        print!("  stop   - Stop the service\n");
        print!("  status - Show service status\n");
    } else if (((__sh_arg(2) == "status".to_string()) || (__sh_arg(2) == "s".to_string())) || (__sh_arg(2) == "-s".to_string())) || (__sh_arg(2) == "--status".to_string()) {
        print!("Service status: Running\n");
    } else {
        println!("Unknown option: {}", __sh_arg(2));
    }
    print!("=== Case Statement with Character Classes ===\n");
    if __sh_fnmatch("[0-9]", &__sh_arg(3)) {
        println!("Single digit: {}", __sh_arg(3));
    } else if __sh_fnmatch("[a-z]", &__sh_arg(3)) {
        println!("Lowercase letter: {}", __sh_arg(3));
    } else if __sh_fnmatch("[A-Z]", &__sh_arg(3)) {
        println!("Uppercase letter: {}", __sh_arg(3));
    } else if __sh_fnmatch("[0-9][0-9]", &__sh_arg(3)) {
        println!("Two digit number: {}", __sh_arg(3));
    } else {
        println!("Other character: {}", __sh_arg(3));
    }
    print!("=== Case Statement with Default Action ===\n");
    if __sh_arg(4) == "red".to_string() {
        print!("Color is red\n");
    } else if __sh_arg(4) == "green".to_string() {
        print!("Color is green\n");
    } else if __sh_arg(4) == "blue".to_string() {
        print!("Color is blue\n");
    }
    print!("=== Case Statement with Commands ===\n");
    if __sh_arg(5) == "ls".to_string() {
        __SH_RC.store(__sh_run("'ls' '-l' '-a'"), Ordering::Relaxed);
    } else if __sh_arg(5) == "date".to_string() {
        __SH_RC.store(__sh_run("'date'"), Ordering::Relaxed);
    } else if __sh_arg(5) == "pwd".to_string() {
        println!("{}", std::env::current_dir().map(|p| p.display().to_string()).unwrap_or_default());
    } else if __sh_arg(5) == "whoami".to_string() {
        __SH_RC.store(__sh_run("'whoami'"), Ordering::Relaxed);
    } else {
        print!("Available commands: ls, date, pwd, whoami\n");
        __SH_RC.store(0, Ordering::Relaxed);
    }
    std::process::ExitCode::from(__SH_RC.load(Ordering::Relaxed) as u8)
}
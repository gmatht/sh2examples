    __SHV_tmpf.with(|v| *v.borrow_mut() = { let __sh_ch = __sh_mktemp(false, "/tmp/clobber_test.XXXXXX"); __SH_RC.store(if __sh_ch.is_empty() { 1 } else { 0 }, Ordering::Relaxed); __sh_ch });

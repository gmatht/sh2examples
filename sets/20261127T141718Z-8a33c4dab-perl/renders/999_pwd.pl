#!/usr/bin/env perl
use strict;
use warnings;

my $__sh_cap; do { $__sh_cap = (do { require File::Basename; File::Basename::basename(do { my $__sh_cap; $__sh_cap = (require Cwd, Cwd::getcwd()); $? = 0 << 8; $__sh_cap }) }); $? = 0 << 8; }; print $__sh_cap, "\n" if defined $__sh_cap;  # line 1
print("exit: " . (($? >> 8)), "\n");  # line 3
$? = 0 << 8;
$? = 0 << 8;

exit $? >> 8;

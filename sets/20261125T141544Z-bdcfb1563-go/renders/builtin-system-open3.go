package main

import (
    "fmt"
    "io"
    "os"
    "os/exec"
    "strings"
)

func s2s(x any) string {
    if x == nil { return "" }
    return fmt.Sprintf("%v", x)
}

func runCmd(c *exec.Cmd) int64 {
    c.Stdout = os.Stdout
    c.Stderr = io.Discard
    if err := c.Run(); err != nil {
        if ee, ok := err.(*exec.ExitError); ok { return int64(ee.ExitCode()) }
        return 1
    }
    return 0
}

func capCmd(c *exec.Cmd) string {
    c.Stderr = io.Discard
    out, err := c.Output()
    if err != nil { return "" }
    return strings.TrimRight(string(out), "\n")
}

func main() {
    var hostname string
    var st int64

    hostname = s2s(capCmd(exec.Command("hostname"))); // line 3
    st = runCmd(exec.Command("cp", "file1", "file2")); // line 4
    fmt.Println(fmt.Sprintf("Hostname: %v", hostname)); // line 5
    st = 0;
    _ = st
    return;
}
package main

import (
    "fmt"
)

func main() {
    var st int64

    fmt.Println("ax/pz ax/qz ayz");
    st = 0;
    fmt.Println("ad bd cd");
    st = 0;
    fmt.Println("src/main/a src/main/b src/test/a src/test/b docs/a docs/b");
    st = 0;
    fmt.Println("file.txt file.bak file.orig");
    st = 0;
    fmt.Println("prexpost preypost");
    st = 0;
    fmt.Println("source.bat source.c");
    st = 0;
    fmt.Print("pre"); // line 18
    st = 0;
    fmt.Println("xpost ypost");
    st = 0;
    fmt.Println(fmt.Sprintf("done: %v", st)); // line 20
    st = 0;
    return;
}
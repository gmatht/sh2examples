use std::sync::atomic::Ordering;

static __SH_RC: std::sync::atomic::AtomicI32 = std::sync::atomic::AtomicI32::new(0);

fn __sh_fnmatch(pat: &str, s: &str) -> bool {
    // bash's pattern matcher treats the pattern as a C string — a NUL
    // truncates it (so `*$'\x00'*` is effectively just `*` and always
    // matches)
    let pat = pat.split('\0').next().unwrap_or(pat);
    let p: Vec<char> = pat.chars().collect();
    let t: Vec<char> = s.chars().collect();
    fn m(p: &[char], t: &[char]) -> bool {
        if p.is_empty() { return t.is_empty(); }
        match p[0] {
            '*' => {
                for i in 0..=t.len() { if m(&p[1..], &t[i..]) { return true; } }
                false
            }
            '?' => !t.is_empty() && m(&p[1..], &t[1..]),
            '[' => {
                if t.is_empty() { return false; }
                let mut j = 1;
                let neg = j < p.len() && (p[j] == '!' || p[j] == '^');
                if neg { j += 1; }
                let mut matched = false;
                let mut first = true;
                while j < p.len() && (p[j] != ']' || first) {
                    first = false;
                    if j + 2 < p.len() && p[j + 1] == '-' && p[j + 2] != ']' {
                        if t[0] >= p[j] && t[0] <= p[j + 2] { matched = true; }
                        j += 3;
                    } else {
                        if t[0] == p[j] { matched = true; }
                        j += 1;
                    }
                }
                if j < p.len() && p[j] == ']' { j += 1; }
                if matched != neg { m(&p[j..], &t[1..]) } else { false }
            }
            '\\' => p.len() > 1 && !t.is_empty() && t[0] == p[1] && m(&p[2..], &t[1..]),
            c if (c == '@' || c == '?' || c == '*' || c == '+' || c == '!')
                && p.len() > 1 && p[1] == '(' => {
                // extglob: parse the group's alternatives
                let mut depth = 1;
                let mut j = 2;
                let mut alts: Vec<Vec<char>> = Vec::new();
                let mut cur: Vec<char> = Vec::new();
                while j < p.len() && depth > 0 {
                    match p[j] {
                        '(' => { depth += 1; cur.push(p[j]); }
                        ')' => {
                            depth -= 1;
                            if depth == 0 {
                                alts.push(cur.clone());
                            } else { cur.push(p[j]); }
                        }
                        '|' if depth == 1 => { alts.push(std::mem::take(&mut cur)); }
                        ch => cur.push(ch),
                    }
                    j += 1;
                }
                if depth != 0 { return false; }
                let rest = &p[j..];
                match c {
                    '@' => {
                        for a in &alts {
                            let mut joined = a.clone();
                            joined.extend_from_slice(rest);
                            if m(&joined, t) { return true; }
                        }
                        false
                    }
                    '?' => {
                        if m(rest, t) { return true; }
                        for a in &alts {
                            let mut joined = a.clone();
                            joined.extend_from_slice(rest);
                            if m(&joined, t) { return true; }
                        }
                        false
                    }
                    '*' => {
                        // *(alts)rest  =  rest  |  a ++ *(alts)rest  (some alt a)
                        if m(rest, t) { return true; }
                        for a in &alts {
                            for i in 1..=t.len() {
                                if m(a, &t[..i]) && m(p, &t[i..]) { return true; }
                            }
                        }
                        false
                    }
                    '+' => {
                        // +(alts)rest  =  a ++ *(alts)rest  (at least one alt a)
                        for a in &alts {
                            for i in 1..=t.len() {
                                if m(a, &t[..i]) && m(p, &t[i..]) { return true; }
                            }
                        }
                        false
                    }
                    _ => {
                        // !(alts)rest: t = t1 ++ t2 with t2 matching rest
                        // and t1 matching NO alternative
                        for i in 0..=t.len() {
                            if m(rest, &t[i..]) {
                                let mut ok = true;
                                for a in &alts {
                                    if m(a, &t[..i]) { ok = false; break; }
                                }
                                if ok { return true; }
                            }
                        }
                        false
                    }
                }
            }
            c => !t.is_empty() && t[0] == c && m(&p[1..], &t[1..]),
        }
    }
    m(&p, &t)
}

fn __sh_regex(text: &str, pat: &str, flags: &str) -> bool {
    let cmd = if flags.contains('i') {
        "shopt -s nocasematch; [[ $1 =~ $2 ]]"
    } else {
        "[[ $1 =~ $2 ]]"
    };
    let mut c = std::process::Command::new("bash");
    c.arg("-c").arg(cmd).arg("sh").arg(text).arg(pat);
    c.status().map(|s| s.success()).unwrap_or(false)
}

fn main() {
    println!("{}", "== [[ pattern and regex ]]".to_string());
    let s = "file.txt";
    __SH_RC.store(0, Ordering::SeqCst);
    if { let __b =  { let __t: &str = {&s}; __t.ends_with(".txt") }; __SH_RC.store(if __b { 0 } else { 1 }, Ordering::SeqCst); __b } {
        print!("{}", "pattern-match\n");
        __SH_RC.store(0, Ordering::SeqCst);
    }
    if { let __b = __sh_regex(&s, "^file\\.[a-z]+$", ""); __SH_RC.store(if __b { 0 } else { 1 }, Ordering::SeqCst); __b } {
        print!("{}", "regex-match\n");
        __SH_RC.store(0, Ordering::SeqCst);
    }
    println!("{}", "== extglob ==".to_string());
    let _ = String::new();
    let f1 = "file.js";
    let f2 = "thing.min.js";
    __SH_RC.store(0, Ordering::SeqCst);
    if { let __b =  __sh_fnmatch("!(*.min).js", &f1); __SH_RC.store(if __b { 0 } else { 1 }, Ordering::SeqCst); __b } {
        print!("{}", "f1-ok\n");
        __SH_RC.store(0, Ordering::SeqCst);
    }
    if !{ let __b =  __sh_fnmatch("!(*.min).js", &f2); __SH_RC.store(if __b { 0 } else { 1 }, Ordering::SeqCst); __b } {
        print!("{}", "f2-filtered\n");
        __SH_RC.store(0, Ordering::SeqCst);
    }
    println!("{}", "== nocasematch ==".to_string());
    let _ = String::new();
    let word = "Foo";
    __SH_RC.store(0, Ordering::SeqCst);
    if { let __b =  __sh_fnmatch(&"foo".to_string().to_lowercase(), &word.to_lowercase()); __SH_RC.store(if __b { 0 } else { 1 }, Ordering::SeqCst); __b } {
        print!("{}", "ci-match\n");
        __SH_RC.store(0, Ordering::SeqCst);
    }
    std::process::exit(__SH_RC.load(Ordering::SeqCst));
}